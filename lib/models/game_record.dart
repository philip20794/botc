import 'dart:convert';

import 'package:crypto/crypto.dart';

/// Public, anonymised representation of a completed BotC game.
///
/// This model deliberately has no player names, notes, character descriptions,
/// UI labels, or raw Chronicle details. It is independent of local persistence
/// and ready for a future Firestore transport layer.
class GameRecord {
  static const currentSchemaVersion = 1;

  final int schemaVersion;
  final String gameId;
  final DateTime startedAt;
  final DateTime endedAt;
  final Duration totalDuration;
  final int playerCount;
  final GameTeam winnerTeam;
  final GameRecordScript script;
  final List<GameRecordPlayer> players;
  final List<GameRecordPhase> phases;
  final List<GameRecordChronicleEvent> chronicleEvents;

  GameRecord({
    this.schemaVersion = currentSchemaVersion,
    required this.gameId,
    required this.startedAt,
    required this.endedAt,
    required this.totalDuration,
    required this.playerCount,
    required this.winnerTeam,
    required this.script,
    required List<GameRecordPlayer> players,
    required List<GameRecordPhase> phases,
    required List<GameRecordChronicleEvent> chronicleEvents,
  })  : players = List.unmodifiable(players),
        phases = List.unmodifiable(phases),
        chronicleEvents = List.unmodifiable(chronicleEvents);

  factory GameRecord.fromJson(Map<String, dynamic> json) => GameRecord(
        schemaVersion: _requiredInt(json, 'schemaVersion'),
        gameId: _requiredString(json, 'gameId'),
        startedAt: _requiredDateTime(json, 'startedAt'),
        endedAt: _requiredDateTime(json, 'endedAt'),
        totalDuration:
            Duration(milliseconds: _requiredInt(json, 'totalDurationMs')),
        playerCount: _requiredInt(json, 'playerCount'),
        winnerTeam: GameTeamJson.fromJson(_requiredString(json, 'winnerTeam')),
        script: GameRecordScript.fromJson(_requiredMap(json, 'script')),
        players:
            _requiredObjectList(json, 'players', GameRecordPlayer.fromJson),
        phases: _requiredObjectList(json, 'phases', GameRecordPhase.fromJson),
        chronicleEvents: _requiredObjectList(
          json,
          'chronicleEvents',
          GameRecordChronicleEvent.fromJson,
        ),
      );

  Map<String, dynamic> toJson() => {
        'schemaVersion': schemaVersion,
        'gameId': gameId,
        'startedAt': startedAt.toIso8601String(),
        'endedAt': endedAt.toIso8601String(),
        'totalDurationMs': totalDuration.inMilliseconds,
        'playerCount': playerCount,
        'winnerTeam': winnerTeam.name,
        'script': script.toJson(),
        'players': players.map((player) => player.toJson()).toList(),
        'phases': phases.map((phase) => phase.toJson()).toList(),
        'chronicleEvents':
            chronicleEvents.map((event) => event.toJson()).toList(),
      };
}

enum GameTeam { good, evil }

extension GameTeamJson on GameTeam {
  static GameTeam fromJson(String value) => GameTeam.values.firstWhere(
        (team) => team.name == value,
        orElse: () => throw FormatException('Unknown winner/team: $value'),
      );
}

class GameRecordScript {
  final String scriptId;
  final String name;
  final bool isCustom;
  final List<String> roleIds;
  final String contentHash;

  GameRecordScript({
    required this.scriptId,
    required this.name,
    required this.isCustom,
    required List<String> roleIds,
    required this.contentHash,
  }) : roleIds = List.unmodifiable(roleIds);

  /// Stable SHA-256 hash over the ordered role list. The role order is part of
  /// a BotC script and is therefore intentionally not sorted.
  static String contentHashForRoleIds(List<String> roleIds) {
    final canonicalJson = jsonEncode({'roleIds': roleIds});
    return sha256.convert(utf8.encode(canonicalJson)).toString();
  }

  factory GameRecordScript.fromJson(Map<String, dynamic> json) =>
      GameRecordScript(
        scriptId: _requiredString(json, 'scriptId'),
        name: _requiredString(json, 'name'),
        isCustom: _requiredBool(json, 'isCustom'),
        roleIds: _requiredStringList(json, 'roleIds'),
        contentHash: _requiredString(json, 'contentHash'),
      );

  Map<String, dynamic> toJson() => {
        'scriptId': scriptId,
        'name': name,
        'isCustom': isCustom,
        'roleIds': roleIds,
        'contentHash': contentHash,
      };
}

/// An opaque participant record. [anonymizedPlayerId] must be generated by the
/// future record builder; it must never be a player name or account identifier.
class GameRecordPlayer {
  final String anonymizedPlayerId;
  final int position;
  final String actualStartRoleId;
  final String displayedStartRoleId;
  final GameTeam startTeam;
  final String endRoleId;
  final GameTeam endTeam;

  const GameRecordPlayer({
    required this.anonymizedPlayerId,
    required this.position,
    required this.actualStartRoleId,
    required this.displayedStartRoleId,
    required this.startTeam,
    required this.endRoleId,
    required this.endTeam,
  });

  factory GameRecordPlayer.fromJson(Map<String, dynamic> json) =>
      GameRecordPlayer(
        anonymizedPlayerId: _requiredString(json, 'anonymizedPlayerId'),
        position: _requiredInt(json, 'position'),
        actualStartRoleId: _requiredString(json, 'actualStartRoleId'),
        displayedStartRoleId: _requiredString(json, 'displayedStartRoleId'),
        startTeam: GameTeamJson.fromJson(_requiredString(json, 'startTeam')),
        endRoleId: _requiredString(json, 'endRoleId'),
        endTeam: GameTeamJson.fromJson(_requiredString(json, 'endTeam')),
      );

  Map<String, dynamic> toJson() => {
        'anonymizedPlayerId': anonymizedPlayerId,
        'position': position,
        'actualStartRoleId': actualStartRoleId,
        'displayedStartRoleId': displayedStartRoleId,
        'startTeam': startTeam.name,
        'endRoleId': endRoleId,
        'endTeam': endTeam.name,
      };
}

enum GameRecordPhaseType { night, day }

class GameRecordPhase {
  final String phaseId;
  final GameRecordPhaseType type;
  final int round;
  final DateTime startedAt;
  final DateTime endedAt;
  final Duration duration;

  const GameRecordPhase({
    required this.phaseId,
    required this.type,
    required this.round,
    required this.startedAt,
    required this.endedAt,
    required this.duration,
  });

  factory GameRecordPhase.fromJson(Map<String, dynamic> json) =>
      GameRecordPhase(
        phaseId: _requiredString(json, 'phaseId'),
        type: GameRecordPhaseType.values.firstWhere(
          (type) => type.name == _requiredString(json, 'type'),
          orElse: () => throw const FormatException('Unknown phase type.'),
        ),
        round: _requiredInt(json, 'round'),
        startedAt: _requiredDateTime(json, 'startedAt'),
        endedAt: _requiredDateTime(json, 'endedAt'),
        duration: Duration(milliseconds: _requiredInt(json, 'durationMs')),
      );

  Map<String, dynamic> toJson() => {
        'phaseId': phaseId,
        'type': type.name,
        'round': round,
        'startedAt': startedAt.toIso8601String(),
        'endedAt': endedAt.toIso8601String(),
        'durationMs': duration.inMilliseconds,
      };
}

enum GameRecordChronicleEventType {
  gameStarted,
  phaseStarted,
  lifeStatusChanged,
  reminderAssigned,
  reminderRemoved,
  quickFlowCharacterSelected,
  quickFlowInfoConfirmed,
  characterChanged,
  nightActionVisited,
  nightInformation,
}

enum GameRecordEventPhase { setup, night, day }

/// Structured, privacy-safe values captured by a Chronicle event. Arbitrary
/// strings and raw Chronicle maps are intentionally not supported.
class GameRecordEventData {
  final Map<String, bool> flags;
  final Map<String, int> numbers;
  final Map<String, List<String>> roleIds;
  final Map<String, List<String>> playerIds;
  final Map<String, List<String>> tokenIds;

  GameRecordEventData({
    Map<String, bool> flags = const {},
    Map<String, int> numbers = const {},
    Map<String, List<String>> roleIds = const {},
    Map<String, List<String>> playerIds = const {},
    Map<String, List<String>> tokenIds = const {},
  })  : flags = Map.unmodifiable(flags),
        numbers = Map.unmodifiable(numbers),
        roleIds = _freezeStringLists(roleIds),
        playerIds = _freezeStringLists(playerIds),
        tokenIds = _freezeStringLists(tokenIds);

  factory GameRecordEventData.fromJson(Map<String, dynamic> json) =>
      GameRecordEventData(
        flags: _optionalBoolMap(json, 'flags'),
        numbers: _optionalIntMap(json, 'numbers'),
        roleIds: _optionalStringListMap(json, 'roleIds'),
        playerIds: _optionalStringListMap(json, 'playerIds'),
        tokenIds: _optionalStringListMap(json, 'tokenIds'),
      );

  Map<String, dynamic> toJson() => {
        if (flags.isNotEmpty) 'flags': flags,
        if (numbers.isNotEmpty) 'numbers': numbers,
        if (roleIds.isNotEmpty) 'roleIds': roleIds,
        if (playerIds.isNotEmpty) 'playerIds': playerIds,
        if (tokenIds.isNotEmpty) 'tokenIds': tokenIds,
      };
}

class GameRecordChronicleEvent {
  final String eventId;
  final DateTime occurredAt;
  final GameRecordChronicleEventType type;
  final GameRecordEventPhase phase;
  final int round;
  final String? actorPlayerId;
  final List<String> targetPlayerIds;
  final GameRecordEventData data;

  GameRecordChronicleEvent({
    required this.eventId,
    required this.occurredAt,
    required this.type,
    required this.phase,
    required this.round,
    this.actorPlayerId,
    List<String> targetPlayerIds = const [],
    GameRecordEventData? data,
  })  : targetPlayerIds = List.unmodifiable(targetPlayerIds),
        data = data ?? GameRecordEventData();

  factory GameRecordChronicleEvent.fromJson(Map<String, dynamic> json) =>
      GameRecordChronicleEvent(
        eventId: _requiredString(json, 'eventId'),
        occurredAt: _requiredDateTime(json, 'occurredAt'),
        type: GameRecordChronicleEventType.values.firstWhere(
          (type) => type.name == _requiredString(json, 'type'),
          orElse: () =>
              throw const FormatException('Unknown Chronicle event type.'),
        ),
        phase: GameRecordEventPhase.values.firstWhere(
          (phase) => phase.name == _requiredString(json, 'phase'),
          orElse: () =>
              throw const FormatException('Unknown Chronicle event phase.'),
        ),
        round: _requiredInt(json, 'round'),
        actorPlayerId: _optionalString(json, 'actorPlayerId'),
        targetPlayerIds: _optionalStringList(json, 'targetPlayerIds'),
        data: json['data'] == null
            ? GameRecordEventData()
            : GameRecordEventData.fromJson(_requiredMap(json, 'data')),
      );

  Map<String, dynamic> toJson() => {
        'eventId': eventId,
        'occurredAt': occurredAt.toIso8601String(),
        'type': type.name,
        'phase': phase.name,
        'round': round,
        if (actorPlayerId != null) 'actorPlayerId': actorPlayerId,
        'targetPlayerIds': targetPlayerIds,
        if (data.toJson().isNotEmpty) 'data': data.toJson(),
      };
}

Map<String, List<String>> _freezeStringLists(Map<String, List<String>> value) =>
    Map<String, List<String>>.unmodifiable({
      for (final entry in value.entries)
        entry.key: List<String>.unmodifiable(entry.value),
    });

String _requiredString(Map<String, dynamic> json, String key) {
  final value = json[key];
  if (value is! String || value.isEmpty) {
    throw FormatException('$key must be a non-empty string.');
  }
  return value;
}

String? _optionalString(Map<String, dynamic> json, String key) {
  final value = json[key];
  if (value == null) return null;
  if (value is! String || value.isEmpty) {
    throw FormatException('$key must be a non-empty string when supplied.');
  }
  return value;
}

int _requiredInt(Map<String, dynamic> json, String key) {
  final value = json[key];
  if (value is! int) throw FormatException('$key must be an integer.');
  return value;
}

bool _requiredBool(Map<String, dynamic> json, String key) {
  final value = json[key];
  if (value is! bool) throw FormatException('$key must be a boolean.');
  return value;
}

DateTime _requiredDateTime(Map<String, dynamic> json, String key) {
  final value = _requiredString(json, key);
  final dateTime = DateTime.tryParse(value);
  if (dateTime == null) throw FormatException('$key must be an ISO timestamp.');
  return dateTime;
}

Map<String, dynamic> _requiredMap(Map<String, dynamic> json, String key) {
  final value = json[key];
  if (value is! Map) throw FormatException('$key must be an object.');
  return Map<String, dynamic>.from(value);
}

List<T> _requiredObjectList<T>(
  Map<String, dynamic> json,
  String key,
  T Function(Map<String, dynamic>) parse,
) {
  final value = json[key];
  if (value is! List) throw FormatException('$key must be a list.');
  return value.map((item) {
    if (item is! Map) throw FormatException('$key must contain objects.');
    return parse(Map<String, dynamic>.from(item));
  }).toList();
}

List<String> _requiredStringList(Map<String, dynamic> json, String key) {
  final value = json[key];
  if (value is! List || value.any((item) => item is! String)) {
    throw FormatException('$key must be a list of strings.');
  }
  return value.cast<String>();
}

List<String> _optionalStringList(Map<String, dynamic> json, String key) {
  if (!json.containsKey(key)) return const [];
  return _requiredStringList(json, key);
}

Map<String, bool> _optionalBoolMap(Map<String, dynamic> json, String key) {
  if (!json.containsKey(key)) return const {};
  final value = _requiredMap(json, key);
  if (value.values.any((item) => item is! bool)) {
    throw FormatException('$key must map strings to booleans.');
  }
  return value.cast<String, bool>();
}

Map<String, int> _optionalIntMap(Map<String, dynamic> json, String key) {
  if (!json.containsKey(key)) return const {};
  final value = _requiredMap(json, key);
  if (value.values.any((item) => item is! int)) {
    throw FormatException('$key must map strings to integers.');
  }
  return value.cast<String, int>();
}

Map<String, List<String>> _optionalStringListMap(
  Map<String, dynamic> json,
  String key,
) {
  if (!json.containsKey(key)) return const {};
  final value = _requiredMap(json, key);
  return value.map((mapKey, item) {
    if (item is! List || item.any((entry) => entry is! String)) {
      throw FormatException('$key must map strings to string lists.');
    }
    return MapEntry(mapKey, item.cast<String>());
  });
}
